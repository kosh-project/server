use crate::Result;
use axum::{Extension, Json, extract::State};
use hyper::StatusCode;

use crate::{
    api::auth::passkey::user_id_to_handle, app, error::JsonResult,
    model::passkey,
};

/// Data transfer objects for initiating passkey registration.
pub mod start {
    use serde::Serialize;
    use uuid::Uuid;
    use webauthn_rs::prelude::CreationChallengeResponse;

    /// Response payload returned by `POST /api/v1/auth/passkey/register/start`.
    ///
    /// The client passes `challenge` directly into `navigator.credentials.create({ publicKey: challenge.publicKey })`.
    #[derive(Serialize)]
    pub struct Response {
        /// Ephemeral challenge identifier used to correlate the finish step with cached ceremony state.
        pub challenge_id: Uuid,
        /// The `WebAuthn` credential creation options generated by the Relying Party.
        pub challenge: CreationChallengeResponse,
    }
}

/// Data transfer objects for completing passkey registration.
pub mod finish {
    use serde::Deserialize;
    use uuid::Uuid;
    use webauthn_rs::prelude::RegisterPublicKeyCredential;

    use crate::api::{self, Error::BadRequest};

    /// Request payload for `POST /api/v1/auth/passkey/register/finish`.
    #[derive(Deserialize)]
    pub struct Request {
        /// Ephemeral challenge identifier returned by [`super::register_start`].
        pub challenge_id: Uuid,
        /// The credential attestation response produced by `navigator.credentials.create()`.
        pub credential: RegisterPublicKeyCredential,
        /// Client-encrypted device label or metadata, hex-encoded (up to 2048 hex chars / 1024 raw bytes).
        pub encrypted_metadata: String,
    }

    impl Request {
        /// Validates and hex-decodes the `encrypted_metadata` string into raw bytes.
        ///
        /// Enforces that the hex string length does not exceed 2048 characters (1024 bytes)
        /// to satisfy database check constraints, and decodes the string into a byte vector.
        ///
        /// # Errors
        ///
        /// - Returns [`BadRequest`] if the string exceeds 2048 hex characters.
        /// - Returns [`BadRequest`] if the string contains invalid hexadecimal digits.
        pub fn parse_metadata(&self) -> api::Result<Vec<u8>> {
            if self.encrypted_metadata.len() > 2048 {
                return Err(BadRequest(
                    "encrypted_metadata can't exceed 2048 hex chars (or 1024 bytes)",
                ));
            }

            let Ok(bytes) = hex::decode(&self.encrypted_metadata) else {
                return Err(BadRequest("Invalid hex encrypted_metadata"))?;
            };

            Ok(bytes)
        }
    }
}

/// Initiates a `WebAuthn` passkey registration ceremony for an authenticated user.
///
/// Route: `POST /api/v1/auth/passkey/register/start` (protected by `mac_guard` and `auth_guard`).
///
/// 1. Queries existing passkeys for the caller to populate `excludeCredentials`, preventing
///    the authenticator from creating duplicate credentials for this account on the same device.
/// 2. Converts the caller's `user_id` into a deterministic `WebAuthn` user handle [`uuid::Uuid`].
/// 3. Generates a registration challenge and caches intermediate registration state with a 60-second `TTL`.
/// 4. Returns the challenge options and ephemeral `challenge_id` to the client.
///
/// # Errors
///
/// - Returns [`crate::api::Error::IntegerConversion`] if the caller's `user_id` is negative.
/// - Returns [`crate::api::Error::WebAuthn`] if challenge generation fails.
/// - Returns [`crate::model::Error::Database`] if querying existing credentials from `SQLite` fails.
pub async fn register_start(
    State(state): State<app::State>,
    Extension(user_id): Extension<i64>,
) -> JsonResult<start::Response> {
    let exclude_credentials =
        passkey::Record::exclude_list_for_user(&state.db, user_id).await?;

    let user_handle = user_id_to_handle(user_id)?;

    let (challenge, reg_state) = state.webauthn.start_passkey_registration(
        user_handle,
        "kosh-user",
        "Kosh Vault User",
        exclude_credentials,
    )?;

    let challenge_id =
        state.passkey.store_registration(user_id, reg_state).await;

    Ok(Json(start::Response {
        challenge_id,
        challenge,
    }))
}

/// Completes a `WebAuthn` passkey registration ceremony and stores the credential.
///
/// Route: `POST /api/v1/auth/passkey/register/finish` (protected by `mac_guard` and `auth_guard`).
///
/// 1. Retrieves and atomically consumes the cached registration state associated with `challenge_id`,
///    verifying that the user ID completing the ceremony matches the user ID that started it.
/// 2. Validates and hex-decodes the client-encrypted metadata payload.
/// 3. Cryptographically verifies the authenticator's attestation response against the cached challenge.
/// 4. Persists the verified credential record to `webauthn_credentials`.
/// 5. Returns HTTP `201 Created` upon success.
///
/// # Errors
///
/// - Returns [`crate::api::Error::BadRequest`] if the challenge ID is invalid or expired.
/// - Returns [`crate::api::Error::Unauthorized`] if the ceremony was started by a different user.
/// - Returns [`crate::api::Error::BadRequest`] if `encrypted_metadata` is malformed hex or exceeds 1024 bytes.
/// - Returns [`crate::api::Error::WebAuthn`] if attestation verification fails.
/// - Returns an internal error if passkey serialization fails.
/// - Returns [`crate::model::Error::UniqueViolation`] if the credential ID is already registered.
/// - Returns [`crate::model::Error::Database`] if database persistence fails.
pub async fn register_finish(
    State(state): State<app::State>,
    Extension(user_id): Extension<i64>,
    Json(request): Json<finish::Request>,
) -> Result<StatusCode> {
    let reg_state = state
        .passkey
        .take_registration(&request.challenge_id, user_id)
        .await?;

    let encrypted_metadata = request.parse_metadata()?;

    let passkey = state
        .webauthn
        .finish_passkey_registration(&request.credential, &reg_state)?;

    let record = passkey::Record::new(user_id, &passkey, encrypted_metadata)?;
    passkey::Record::create(&state.db, &record).await?;

    Ok(StatusCode::CREATED)
}
